#include <unistd.h>

void	escribe(char *str)
{
	int	i;

	i = 0;
	while(str[i] != '\0')
	{
		write(1, &str[i], 1);
		i++; 
	}
}

int	main(void)
{
	escribe("hola");
	return (0);
}